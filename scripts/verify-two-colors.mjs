import {chromium} from '@playwright/test';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.addInitScript(()=>localStorage.setItem('evo-cookie-choice','essential'));
await page.goto('http://127.0.0.1:3014');
await page.locator('h1').waitFor();
if(await page.locator('.hero-pagination button').count()!==2)throw Error('Expected two colors');
await page.getByRole('button',{name:'Banner 2',exact:true}).click();
const img=page.locator('.hero-product img');
await img.evaluate(el=>el.decode());
if(!(await img.getAttribute('src')).includes('evo-grand-lite-white'))throw Error('White not selected');
await page.screenshot({path:'docs/screenshots/white-hero-desktop.png'});
await page.getByRole('button',{name:'Banner tiếp theo',exact:true}).click();
if(!(await img.getAttribute('src')).includes('evo-grand-lite-lavender'))throw Error('Next did not wrap');
await page.getByRole('button',{name:'Banner trước',exact:true}).click();
if(!(await img.getAttribute('src')).includes('evo-grand-lite-white'))throw Error('Previous did not wrap');
await page.setViewportSize({width:390,height:844});
await img.evaluate(el=>el.decode());
if(!(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)))throw Error('Mobile overflow');
await page.screenshot({path:'docs/screenshots/white-hero-mobile.png',fullPage:true});
console.log('PASS: two colors, white image loaded, next/previous wrap, mobile no overflow');
await browser.close();
